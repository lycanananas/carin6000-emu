static inline const unsigned char *font_glyph(char c)
{
	if (c >= 'a' && c <= 'z')
		c -= 'a' - 'A';
	if (c < FONT_FIRST || c > FONT_LAST)
		c = '?';
	return font_data[c - FONT_FIRST];
}
